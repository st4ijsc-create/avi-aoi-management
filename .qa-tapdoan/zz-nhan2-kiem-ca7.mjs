import { execFileSync } from "node:child_process";
execFileSync("npx",["esbuild","client/src/components/twin3d/van-hanh/datNhanSaBan.ts","--format=esm","--bundle","--outfile=.qa-tapdoan/zz-nhan2-datnhan-sau.mjs"],{stdio:"pipe",shell:true});
const { datNhanSaBan } = await import("./zz-nhan2-datnhan-sau.mjs");
const KHUNG={rong:968,cao:489}, CO={rong:60,cao:18};
const THE={trai:0,phai:470,tren:34,duoi:400};
const KHOI={trai:420,phai:560,tren:300,duoi:380};
const hop=(d)=>({trai:d.x-CO.rong/2,phai:d.x+CO.rong/2,tren:d.y-CO.cao/2,duoi:d.y+CO.cao/2});
const giao=(a,b)=>Math.max(0,Math.min(a.phai,b.phai)-Math.max(a.trai,b.trai))*Math.max(0,Math.min(a.duoi,b.duoi)-Math.max(a.tren,b.tren));
const d=datNhanSaBan(KHOI,CO,[THE],KHUNG,"trong");
const h=hop(d);
console.log("SAU VÁ  :",JSON.stringify(d));
console.log("  hộp chữ:",JSON.stringify(h));
console.log("  giao với THE =",giao(h,THE),"px²  ⇒",giao(h,THE)===0?"SẠCH TRỌN ✓":"CÒN CHE ✗");
console.log("  trong khung:",h.trai>=0&&h.phai<=KHUNG.rong&&h.tren>=0&&h.duoi<=KHUNG.cao);
console.log("  cách mép DƯỚI khối:",(h.tren-KHOI.duoi).toFixed(1),"px (neo `duoi` cách 6 px; trần trượt 40)");
// tuyến cũ để so
const cu={x:530,y:285}, hc=hop(cu);
console.log("TRƯỚC VÁ:",JSON.stringify(cu),"ma=tren-phai");
console.log("  hộp chữ:",JSON.stringify(hc),"giao =",giao(hc,THE),"px²");
console.log("  cách mép TRÊN khối:",(KHOI.tren-hc.duoi).toFixed(1),"px; lệch tâm ngang:",(cu.x-(KHOI.trai+KHOI.phai)/2).toFixed(1),"px");
