import "./dom.mjs";
import { test, afterEach } from "node:test";
import assert from "node:assert/strict";
import { render, act, cleanup, screen } from "@testing-library/react";
import { PhongTheoDoi } from "./sol.mjs";
afterEach(cleanup);
test("chi ket noi lai khi doi phong; dung props moi nhat khi nhan gia tri", async () => {
  const mo: string[] = [], dong: string[] = [];
  let phat: ((v: number) => void) | null = null;
  const ketNoi = (phong: string, cb: (v: number) => void) => { mo.push(phong); phat = cb; return () => { dong.push(phong); }; };
  const bd1: string[] = [], bd2: string[] = [];
  let r: any;
  await act(async () => { r = render(<PhongTheoDoi phong="A" donVi="C" nguong={50} baoDong={(s: string) => bd1.push(s)} ketNoi={ketNoi} />); });
  assert.ok(screen.getByText("Phòng A"));
  assert.deepEqual(mo, ["A"]);
  await act(async () => { phat!(40); phat!(60); });
  assert.deepEqual(bd1, ["A: 60.0°C"]);
  await act(async () => { r.rerender(<PhongTheoDoi phong="A" donVi="F" nguong={70} baoDong={(s: string) => bd2.push(s)} ketNoi={(p: string, cb: any) => ketNoi(p, cb)} />); });
  assert.deepEqual(mo, ["A"], "doi donVi/nguong/baoDong/ketNoi KHONG duoc ket noi lai");
  assert.deepEqual(dong, []);
  await act(async () => { phat!(60); phat!(80); });
  assert.deepEqual(bd1, ["A: 60.0°C"], "khong duoc goi baoDong cu");
  assert.deepEqual(bd2, ["A: 176.0°F"]);
  await act(async () => { r.rerender(<PhongTheoDoi phong="B" donVi="F" nguong={70} baoDong={(s: string) => bd2.push(s)} ketNoi={ketNoi} />); });
  assert.deepEqual(mo, ["A", "B"]);
  assert.deepEqual(dong, ["A"]);
  await act(async () => { phat!(100); });
  assert.deepEqual(bd2, ["A: 176.0°F", "B: 212.0°F"]);
  r.unmount();
  assert.deepEqual(dong, ["A", "B"]);
});
