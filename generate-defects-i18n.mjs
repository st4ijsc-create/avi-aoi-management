function buildCatalogBlock(lang) {
  const out = {};
  for (const r of CATALOG) {
    out[r.code] = { name: r[lang].name, description: r[lang].description };
  }
  return out;
}

const FILES = [
  { lang: "en", path: "client/src/i18n/locales/en.json" },
  { lang: "vi", path: "client/src/i18n/locales/vi.json" },
  { lang: "zh", path: "client/src/i18n/locales/zh.json" },
];

let totalCodes = 0;
for (const { lang, path: rel } of FILES) {
  const full = path.join(__dirname, rel);
  const raw = fs.readFileSync(full, "utf8");
  const json = JSON.parse(raw);
  if (!json.defects || typeof json.defects !== "object") {
    json.defects = {};
  }
  const block = buildCatalogBlock(lang);
  json.defects.catalog = block;
  // Pretty-print with 2-space indent and trailing newline (matches existing style).
  const next = JSON.stringify(json, null, 2) + "\n";
  fs.writeFileSync(full, next, { encoding: "utf8" });
  totalCodes = Object.keys(block).length;
  console.log(`[i18n] ${lang}: wrote defects.catalog with ${Object.keys(block).length} codes -> ${rel}`);
}

console.log(`\nDone. ${totalCodes} defect codes x 3 locales (en/vi/zh).`);
