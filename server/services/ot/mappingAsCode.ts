/** File YAML không qua được zod/parse — `issues` liệt kê từng lỗi. */
export class MappingValidationError extends Error {
  readonly issues: string[];
  constructor(issues: string[]) {
    super(`Mapping file không hợp lệ: ${issues.join("; ")}`);
    this.name = "MappingValidationError";
    this.issues = issues;
  }
}

export type MappingImportErrorCode = "ADAPTER_NOT_FOUND" | "VERSION_REGRESSION" | "DB_UNAVAILABLE";

/** Lỗi nghiệp vụ khi import (adapter không tồn tại / version thụt lùi / mất DB). */
export class MappingImportError extends Error {
  readonly code: MappingImportErrorCode;
  constructor(code: MappingImportErrorCode, message: string) {
    super(message);
    this.name = "MappingImportError";
    this.code = code;
  }
}

// ─── File schema (zod — chặt, .strict() từ chối field lạ) ─────────────────────

const DATATYPES = ["bool", "int", "float", "string", "json"] as const; // khớp otdatatypeenum

const transformSchema = z
  .object({
    rename: z.string().min(1).max(255).optional(),
    scale: z.number().finite().optional(),
    offset: z.number().finite().optional(),
    unit: z.string().max(50).optional(),
    cast: z.enum(["number", "bool", "string"]).optional(),
    deadband: z.number().min(0).optional(),
  })
  .strict();

const fileTagSchema = z
  .object({
    name: z.string().min(1).max(128),
    address: z.string().min(1).max(255),
    datatype: z.enum(DATATYPES),
    unit: z.string().max(50).nullable().optional(),
    scale: z.number().finite().nullable().optional(),
    offset: z.number().finite().nullable().optional(),
    writable: z.boolean().default(false),
    enabled: z.boolean().default(true),
    deadband: z.number().positive().nullable().optional(),
    sampling_ms: z.number().int().min(1).max(86_400_000).nullable().optional(),
  })
  .strict();

const fileUnsMappingSchema = z
  .object({
    tag: z.string().min(1).max(128),
    uns_topic: z.string().min(1).max(500),
    sparkplug_metric: z.string().max(255).nullable().optional(),
    enabled: z.boolean().default(true),
    transform: transformSchema.nullable().optional(),
    notes: z.string().max(4000).nullable().optional(),
  })
  .strict();

export const mappingFileSchema = z
  .object({
    version: z.number().int().min(1),
    adapter: z.string().min(1).max(64),
    machine: z.string().max(50).nullable().optional(),
    vendor: z.string().max(64).nullable().optional(),
    tags: z.array(fileTagSchema).default([]),
    uns_mappings: z.array(fileUnsMappingSchema).default([]),
  })
  .strict()
  .superRefine((file, ctx) => {
    const tagNames = new Set<string>();
    for (const t of file.tags) {
      if (tagNames.has(t.name)) {
        ctx.addIssue({ code: z.ZodIssueCode.custom, message: `tag trùng lặp: "${t.name}"`, path: ["tags"] });
      }
      tagNames.add(t.name);
    }
    const mapTags = new Set<string>();
    for (const m of file.uns_mappings) {
      if (mapTags.has(m.tag)) {
        ctx.addIssue({ code: z.ZodIssueCode.custom, message: `uns_mapping trùng lặp cho tag "${m.tag}"`, path: ["uns_mappings"] });
      }
      mapTags.add(m.tag);
    }
  });

